/** @param {unknown} input @param {PidConfig} base @returns {PidConfig} */
/* Valida tipos y rangos; conserva campos compatibles pero fija el crucero
 * normal a 100 %. Los límites de fallas se aplican por separado. */
export function validatePidConfig(input,base=PID_DEFAULTS){
  if(!input||typeof input!=='object'||Array.isArray(input))throw Error('Configuración PID inválida.');
  const next={...base};
  for(const [key,value] of Object.entries(input)){
    if(!Object.hasOwn(PID_DEFAULTS,key))throw Error('Parámetro PID desconocido: '+key);
    if(key==='forwardIncreasesDistance'){
      if(typeof value!=='boolean')throw Error('Seleccioná la polaridad del sensor.');
    }else if(typeof value!=='number'||!Number.isFinite(value))throw Error('Los parámetros PID deben ser números finitos.');
    next[key]=value;
  }
  if(next.targetCm<2||next.targetCm>400)throw Error('Distancia objetivo: 2 a 400 cm.');
  if(next.toleranceCm<0.1||next.toleranceCm>5)throw Error('Tolerancia: 0,1 a 5 cm.');
  if(!Number.isInteger(next.minPercent)||!Number.isInteger(next.maxPercent)||next.minPercent<0||
    next.maxPercent>100||next.maxPercent<1||next.minPercent>next.maxPercent)throw Error('Velocidad: 0 ≤ mínimo ≤ máximo ≤ 100 %.');
  if(!Number.isInteger(next.initialPercent)||next.initialPercent<1||next.initialPercent>100)throw Error('Velocidad inicial: 1 a 100 %. Se limita al rango configurado.');
  for(const key of ['kp','ki','kd'])if(next[key]<0||next[key]>10000)throw Error('Ganancias PID: 0 a 10000.');
  if(!Number.isInteger(next.sampleMs)||next.sampleMs<50||next.sampleMs>2000)throw Error('Muestreo: 50 a 2000 ms enteros.');
  for(const key of ['inputScale','outputScale'])if(next[key]<1e-6||next[key]>10000)throw Error('Escala del modelo: 0,000001 a 10000.');
  // Retain the existing config fields on the wire for old clients, but never
  // let a previous speed selection lower automatic cruise or its 100% ceiling.
  next.initialPercent=PID_BASE_PERCENT;next.minPercent=0;next.maxPercent=PID_BASE_PERCENT;
  return next;
}
