/** @typedef {{dir:'FWD'|'REV'|'STOP', v:number, m:number, rpm_m:number, rpm_r:number,
 * vel_r:number, dist:number|null, pos:number|null, state:string,
 * rpm_t:number|null, vel_t:number|null, err:number|null}} Telemetry */

/** @param {unknown} value @returns {number|null} */
function number(value) {
  if (value===null || value===undefined || value==='' || (typeof value!=='number' && typeof value!=='string')) return null;
  const result=Number(value);
  return Number.isFinite(result)?result:null;
}

/** Accepts the original DIR=... line or equivalent JSON. Optional theoretical
 * values are received references; they are NEVER generated by this adapter.
 * @param {unknown} input @returns {Telemetry|null} */
/* Admite ASCII DIR=... o JSON; valida campos físicos y devuelve null
 * si la trama es incoherente. No inventa referencias teóricas ausentes. */
export function parseTelemetry(input) {
  let source=input;
  if (typeof input==='string') {
    const line=input.trim();
    if (line.startsWith('{')) {try {source=JSON.parse(line);} catch {return null;}}
    else if (line.startsWith('DIR=')) source=Object.fromEntries(line.split(',').map(part=>{
      const index=part.indexOf('=');return index<0?['','']:[part.slice(0,index).trim(),part.slice(index+1).trim()];
    }));
    else return null;
  }
  if (!source || typeof source!=='object' || Array.isArray(source)) return null;
  if (source.type==='telemetry' && source.data) source=source.data;
  const fields=Object.fromEntries(Object.entries(source).map(([key,value])=>[key.toLowerCase(),value]));
  const dir=fields.dir;
  if (!['FWD','REV','STOP'].includes(dir) || typeof fields.state!=='string' || !/^[A-Z_]{1,32}$/.test(fields.state)) return null;
  const values={};
  for (const key of ['v','m','rpm_m','rpm_r','vel_r','dist','pos','rpm_t','vel_t','err']) values[key]=number(fields[key]);
  if (['v','m','rpm_m','rpm_r','vel_r'].some(key=>values[key]===null)) return null;
  if (values.v<0 || values.v>100 || ![2,4,8,16].includes(values.m) || values.rpm_m<0 || values.rpm_r<0 || values.vel_r<0) return null;
  for (const key of ['pos','dist','rpm_t','vel_t','err']) {
    if (fields[key]!==undefined && fields[key]!==null && fields[key]!=='NA' && values[key]===null) return null;
  }
  return /** @type {Telemetry} */ ({...values,dir,state:fields.state});
}

/** @param {unknown} input @returns {string|null} */
/* Lista permitida de órdenes web: rechaza comandos desconocidos o concatenados. */
export function normalizeCommand(input) {
  if (typeof input!=='string') return null;
  const command=input.trim().toUpperCase();
  return /^(F|R|S|E|STATUS|M(?:2|4|8|16)|V(?:100|[1-9]?\d))$/.test(command)?command:null;
}

/** Only actual, fresh motor telemetry authorizes a microstep change.
 * @param {Telemetry|null} telemetry @param {number} ageMs */
/* Exige parada física confirmada y una muestra reciente para cambiar micropaso. */
export function canChangeMicrostep(telemetry,ageMs) {
  return Boolean(telemetry && ageMs<=CONTROL.staleMs && telemetry.dir==='STOP' && telemetry.rpm_m===0 && telemetry.state!=='RAMP');
}

/** Match known replies, not unrelated startup text or malformed telemetry.
 * @param {string} command @param {string} line @returns {'ack'|'rejected'|null} */
/* Relaciona respuestas ASCII del firmware con el comando pendiente. */
export function matchReply(command,line) {
  const reply=line.trim();
  if ((command==='F' && /^Direccion:\s*ADELANTE$/i.test(reply)) ||
      (command==='R' && /^Direccion:\s*REVERSA$/i.test(reply)) ||
      (command==='S' && /^STOP$/i.test(reply)) ||
      (command==='E' && /^STOP INMEDIATO$/i.test(reply))) return 'ack';
  if (command[0]==='V' && new RegExp('^Velocidad:\\s*'+Number(command.slice(1))+'%$','i').test(reply)) return 'ack';
  if (command[0]==='M') {
    if (new RegExp('^Microstep:\\s*1/'+Number(command.slice(1))+'$','i').test(reply)) return 'ack';
    if (/^(Detener \(S\) antes de cambiar M|Use M2 M4 M8 M16)/i.test(reply)) return 'rejected';
  }
  return null;
}

